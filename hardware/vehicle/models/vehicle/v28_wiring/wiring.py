def build(z0, sensor=None):
    """{그룹 key: [Part]} + 전선 목록. sensor = 센서 모듈 dict (라이다 · GNSS · 표시등 케이블 끝점)."""
    assert abs(z0 - Z0) < 1e-6, f"바닥 높이가 다르다 {z0} != {Z0}"
    P = parts()
    L = wires() + module_wires()
    # 간선 지름 = 묶인 전선 바깥지름 제곱합 → 다발 지름 × 1.25 + 밴드 2
    for name in TRUNKS:
        ds = [w.d for w in L if w.trunk and w.trunk[0] == name]
        _TD[name] = math.sqrt(sum(d * d for d in ds)) * 1.25 + 2.0 if ds else 6.0
    L = wires() + module_wires()                                 # 간선 z 를 지름에 맞춰 다시
    groups = {k: [] for k in GROUPS}
    for k, v in P.items():
        groups[k] += v
    for name, (y, z, xa, xb, _) in TRUNKS.items():
        zz = trunk_z(name) if z is None else z
        h = tube([(xa, y, zz), (xb, y, zz)], _TD[name])
        h.label = f"간선_{name}_Ø{_TD[name]:.0f}"
        groups["harness"].append(h)
    for w in L:
        for i, leg in enumerate(w.legs()):
            t_ = tube(leg, w.d)
            t_.label = w.label + ("" if i == 0 else "_뒤가지")
            groups[w.grp].append(t_)
        if w.inline:
            nm, si, which, off = (tuple(w.inline) + ("a", (0, 0, 0)))[:4] if len(w.inline) < 4 else w.inline
            leg = w.b if which == "b" else w.a
            a, b = np.asarray(leg[si - 1], float), np.asarray(leg[si], float)
            v = b - a
            ax = int(np.argmax(np.abs(v)))
            c = (a + b) / 2 + np.asarray(off, float)
            size = [8.2, 8.2, 8.2]
            size[ax] = 32.0
            other = [i for i in range(3) if i != ax and i != 2]
            if other:
                size[other[0]] = 15.5
            p = _box(tuple(c), tuple(size))
            p.label = f"커넥터_{nm}"
            groups["connector"].append(p)
    return groups, L


