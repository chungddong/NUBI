class W:
    """전선 · 케이블 하나. a (가지 1) [+ 간선 구간] [+ b (가지 2)]."""

    def __init__(self, grp, label, kind, a, ends=(), trunk=None, b=None, note="", inline=None):
        self.grp, self.label, self.kind, self.a, self.ends = grp, label, kind, a, tuple(ends)
        self.trunk, self.b, self.note, self.inline = trunk, b or [], note, inline
        self.d = OD[kind]

    def legs(self):
        return [p for p in (self.a, self.b) if len(p) >= 2]

    def length(self):
        L = sum(plen(p) for p in self.legs())
        if self.trunk:
            name, xa, xb = self.trunk
            L += abs(xa - xb)
        return L


